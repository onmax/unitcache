export interface PlanningFormatOptions4 { precision?: number, unit?: string, locale?: string }

export function formatPlanning4 (value: number | string | undefined, options: PlanningFormatOptions4 = {}): string {
  if (value === undefined || value === '') return '-'
  const n = typeof value === 'string' ? Number.parseFloat(value) : value
  if (Number.isNaN(n)) return String(value)
  const fixed = n.toFixed(options.precision ?? 1)
  return options.unit ? `${fixed} ${options.unit}` : fixed
}

export function groupPlanning4<T extends { status: string }> (items: T[]): Record<string, T[]> {
  const out: Record<string, T[]> = {}
  for (const item of items) (out[item.status] ??= []).push(item)
  return out
}

export const planningThresholds4 = Object.freeze({ low: 2, mid: 32, high: 98 })
